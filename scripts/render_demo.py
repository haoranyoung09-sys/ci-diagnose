#!/usr/bin/env python3
"""Render the README demo from a real diagnose report.

The SVGs are generated. They are not a screen recording of github.com.
Run: python3 scripts/render_demo.py
"""

from __future__ import annotations

import html
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = "npm-ci-lockfile-drift"


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"missing {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def load_report() -> tuple[str, dict]:
    diagnose = _load("diagnose", ROOT / "scripts" / "diagnose.py")
    fixture = diagnose.load_fixture(ROOT / "fixtures" / "gha" / FIXTURE)
    report = diagnose.diagnose_fixture(fixture)
    text = diagnose.format_report(report).rstrip() + "\n"
    return text, report


def _wrap(line: str, width: int = 88) -> list[str]:
    if len(line) <= width:
        return [line]
    rows: list[str] = []
    rest = line
    while rest:
        rows.append(rest[:width])
        rest = rest[width:]
    return rows


def build_terminal_svg(text: str) -> str:
    """Animated terminal. Each line fades in, in order, then stays."""
    rows: list[str] = []
    for line in text.splitlines():
        rows.extend(_wrap(line))
    width = 760
    line_height = 18
    top = 46
    height = top + 16 + line_height * len(rows)
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img">',
        "<title>CI Doctor terminal demo</title>",
        "<desc>Generated by scripts/render_demo.py from fixtures/gha/npm-ci-lockfile-drift. Not a recording of github.com.</desc>",
        '<rect width="100%" height="100%" rx="12" fill="#0f1419"/>',
        '<rect width="100%" height="32" rx="12" fill="#1c2430"/>',
        '<rect y="16" width="100%" height="16" fill="#1c2430"/>',
        '<circle cx="18" cy="16" r="5" fill="#f07178"/>',
        '<circle cx="36" cy="16" r="5" fill="#ffcc66"/>',
        '<circle cx="54" cy="16" r="5" fill="#c3e88d"/>',
        '<text x="72" y="21" fill="#9aa4b2" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="13">python3 scripts/diagnose.py --fixture npm-ci-lockfile-drift</text>',
    ]
    for index, row in enumerate(rows):
        y = top + index * line_height
        begin = f"{index * 0.12:.2f}s"
        parts.append(
            f'<text x="16" y="{y}" fill="#e6edf3" opacity="0" '
            'font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="13">'
            f"{html.escape(row)}"
            f'<animate attributeName="opacity" from="0" to="1" begin="{begin}" dur="0.08s" fill="freeze"/>'
            "</text>"
        )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def build_summary_svg(report: dict) -> str:
    """Static card of the job-summary fields. Not a GitHub UI screenshot."""
    evidence = report.get("evidence") or []
    steps = report.get("next_steps") or []
    first = str(steps[0]) if steps else ""
    body = [
        "CI Doctor  ·  job summary",
        "Advisory classification. Not a merge decision.",
        "",
        f"category     {report['category']}",
        f"confidence   {float(report['confidence']):.2f} ({report['confidence_level']})",
        "advisory     classification only; not a merge decision",
        "",
        "Evidence",
    ]
    for item in evidence:
        body.extend(_wrap(f"L{item['line']}  {item['text']}", 86))
    body.append("")
    body.append("Next step")
    body.extend(_wrap(first, 86))
    width = 760
    line_height = 20
    top = 56
    height = top + 20 + line_height * len(body)
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img">',
        "<title>CI Doctor job summary</title>",
        "<desc>Rendered by scripts/render_demo.py from the diagnose report for npm-ci-lockfile-drift. Not a screenshot of GitHub.</desc>",
        '<rect width="100%" height="100%" rx="12" fill="#f6f8fa"/>',
        '<rect width="100%" height="40" rx="12" fill="#fff1e6"/>',
        '<rect y="20" width="100%" height="20" fill="#fff1e6"/>',
        '<text x="20" y="26" fill="#9a3412" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="14">Generated from the diagnose report. Not a GitHub screenshot.</text>',
    ]
    for index, row in enumerate(body):
        y = top + index * line_height
        parts.append(
            '<text x="20" y="'
            + str(y)
            + '" fill="#1f2328" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="14">'
            + html.escape(row)
            + "</text>"
        )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def main() -> None:
    text, report = load_report()
    terminal = ROOT / "docs" / "demo-terminal.svg"
    summary = ROOT / "docs" / "demo-summary.svg"
    terminal.write_text(build_terminal_svg(text), encoding="utf-8")
    summary.write_text(build_summary_svg(report), encoding="utf-8")
    print(f"wrote {terminal.relative_to(ROOT)}")
    print(f"wrote {summary.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
